package wallet

import (
	"cmp"
	"context"
	"crypto/rand"
	"errors"
	"fmt"
	"net/http"
	"net/url"
	"strings"
	"time"

	"github.com/Masterminds/semver/v3"
	sdk "github.com/formancehq/formance-sdk-go/v3"
)

type LedgerOptions struct {
	// APIVersion accepts v2, v3, or auto. An empty value uses v2.
	APIVersion string
	// URL is the Ledger service base, including a gateway mount if applicable.
	URL string
	// V3CursorKey is a shared signing secret of at least 32 bytes.
	V3CursorKey string
	// V3Provisioning accepts managed or verify. An empty value uses managed.
	V3Provisioning      string
	IndexedMetadataKeys []string
	// V3IndexStatusURLs lists additional individual Ledger replica service URLs.
	V3IndexStatusURLs []string
}

func selectLedger(ctx context.Context, client *http.Client, stackURL string, options LedgerOptions) (Ledger, error) {
	version := cmp.Or(options.APIVersion, "v2")
	switch version {
	case "v2", "v3", "auto":
	default:
		return nil, fmt.Errorf("invalid Ledger API version %q, expected v2, v3, or auto", version)
	}

	if version == "v2" && options.URL == "" {
		return NewDefaultLedger(sdk.New(sdk.WithClient(client), sdk.WithServerURL(stackURL))), nil
	}

	serviceURL := options.URL
	if serviceURL == "" && stackURL != "" {
		serviceURL = strings.TrimRight(stackURL, "/") + "/api/ledger"
	}
	base, err := parseLedgerURL(serviceURL)
	if err != nil {
		return nil, err
	}

	// Keep version checks and writes on the configured endpoint.
	ledgerClient := *client
	ledgerClient.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }
	if version == "auto" {
		detectCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
		defer cancel()
		version, err = detectLedgerVersion(detectCtx, &ledgerClient, base)
		if err != nil {
			return nil, fmt.Errorf("detect Ledger API version at %s: %w", base, err)
		}
	}
	if version == "v3" {
		key := []byte(options.V3CursorKey)
		switch {
		case len(key) == 0:
			key = make([]byte, 32)
			if _, err := rand.Read(key); err != nil {
				return nil, fmt.Errorf("generate Ledger v3 cursor signing key: %w", err)
			}
		case len(key) < 32:
			return nil, fmt.Errorf("Ledger v3 cursor signing key must be at least 32 bytes")
		}
		return &ledgerV3{client: &ledgerClient, base: base, cursorKey: key}, nil
	}

	origin := *base
	origin.Path, origin.RawPath = "", ""
	return NewDefaultLedger(sdk.New(sdk.WithClient(ledgerV2Endpoint{client: &ledgerClient, base: base}),
		sdk.WithServerURL(origin.String()))), nil
}

func parseLedgerURL(value string) (*url.URL, error) {
	base, err := url.Parse(value)
	if err != nil || (base.Scheme != "http" && base.Scheme != "https") || base.Host == "" ||
		base.User != nil || base.RawQuery != "" || base.ForceQuery || base.Fragment != "" {
		return nil, fmt.Errorf("Ledger endpoint must be an HTTP(S) service URL without credentials, query, or fragment")
	}
	return base, nil
}

// ledgerV2Endpoint removes the Stack mount generated by the SDK before applying
// the configured Ledger service base. The default v2 path uses the SDK directly.
type ledgerV2Endpoint struct {
	client *http.Client
	base   *url.URL
}

func (c ledgerV2Endpoint) Do(req *http.Request) (*http.Response, error) {
	path, ok := strings.CutPrefix(req.URL.EscapedPath(), "/api/ledger/")
	if !ok {
		return nil, fmt.Errorf("unexpected Ledger v2 SDK request path")
	}
	copied := req.Clone(req.Context())
	copied.URL = c.base.JoinPath(path)
	copied.URL.RawQuery = req.URL.RawQuery
	return c.client.Do(copied)
}

func detectLedgerVersion(ctx context.Context, client *http.Client, base *url.URL) (string, error) {
	for _, route := range []string{"_info", "_/info", "v2/_info"} {
		var info struct {
			Version         string `json:"version"`
			ProtocolVersion string `json:"protocolVersion"`
			Data            struct {
				Server  string `json:"server"`
				Version string `json:"version"`
			} `json:"data"`
		}
		err := ledgerJSON(ctx, client, http.MethodGet, base.JoinPath(route), nil, "", http.StatusOK, &info)
		if failure, ok := errors.AsType[*ledgerV3Error](err); ok && failure.Status == http.StatusNotFound {
			continue
		}
		if err != nil {
			return "", fmt.Errorf("GET /%s: %w", route, err)
		}
		version, err := semver.StrictNewVersion(strings.TrimPrefix(cmp.Or(info.Version, info.Data.Version), "v"))
		if err == nil {
			switch {
			case version.Major() == 3 && info.ProtocolVersion != "" && info.Version != "":
				return "v3", nil
			case version.Major() == 2 && info.Data.Server == "ledger" && info.Version == "":
				return "v2", nil
			}
		}
		return "", fmt.Errorf("GET /%s returned unrecognized Ledger version information", route)
	}
	return "", fmt.Errorf("no Ledger version endpoint found, check the service URL or choose v2 or v3 explicitly")
}
